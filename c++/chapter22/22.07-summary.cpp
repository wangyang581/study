// ▼ 问题 1
// 说明应当在什么情况下使用下列各种指针。
//
// 1a) std::unique_ptr

// 【答案 · 查看答案】
// 当你希望用一个智能指针管理某个不会被共享的动态对象时，应当使用
// std::unique_ptr。
//
// 1b) std::shared_ptr

// 【答案 · 查看答案】
// 当你希望用一个智能指针管理某个可能被共享的动态对象时，应当使用
// std::shared_ptr。直到所有持有该对象的std::shared_ptr都被销毁，这个对象才会
// 被释放。
//
// 1c) std::weak_ptr

// 【答案 · 查看答案】
// 当你希望访问某个由std::shared_ptr管理的对象，但又不希望把自己的生命周期与该
// std::shared_ptr绑定在一起时，应当使用std::weak_ptr。
//
// 1d) std::auto_ptr

// 【答案 · 查看答案】
// std::auto_ptr已被弃用，并在C++17中被移除，不应当再使用。

// ▼ 问题 2
// 说明为什么移动语义是围绕右值展开的。

// 【答案 · 查看答案】
// 因为右值是临时的，我们知道它们在使用之后就会被销毁。按值传递或返回右值时，
// 先拷贝再销毁原对象是一种浪费。相反，我们可以直接移动（窃取）右值的资源，这
// 通常更高效。

