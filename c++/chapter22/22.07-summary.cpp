// 下面这段代码有什么问题？请把程序改成符合最佳实践的写法。
//
// 3a)

// [代码 1]
// #include <iostream>
// #include <memory> // 用于 std::shared_ptr
//
// class Resource
// {
// public:
// 	Resource() { std::cout << "Resource acquired\n"; }
// 	~Resource() { std::cout << "Resource destroyed\n"; }
// };
//
// int main()
// {
// 	auto* res{ new Resource{} };
// 	std::shared_ptr<Resource> ptr1{ res };
// 	std::shared_ptr<Resource> ptr2{ res };
//
// 	return 0;
// }


// 【答案 · 查看答案】
// `ptr2`是由`res`而不是由`ptr1`创建的。这意味着现在有两个std::shared_ptr各自
// 独立地试图管理这个`Resource`（它们彼此并不知道对方）。当其中一个离开作用域
// 时，另一个就会持有悬空指针。
//
// `ptr2`应当改为用`ptr1`初始化，而不是用`res`。这样`ptr1`和`ptr2`就能共享
// `res`的所有权。同时应当使用`std::make_shared()`，而不是手工动态分配。

