// 使用派生类的最大好处之一，是能够复用已经编写好的代码。您可以继承基类功能，
// 然后添加新功能、修改现有功能，或隐藏不需要的功能。在这节课和接下来的几节课
// 中，我们将更仔细地了解这些事情分别是如何完成的。
//
// 首先，让我们从一个简单的基类开始：

// [代码 1]
// #include <iostream>
//
// class Base
// {
// protected:
//     int m_value {};
//
// public:
//     Base(int value)
//         : m_value { value }
//     {
//     }
//
//     void identify() const { std::cout << "I am a Base\n"; }
// };

// 现在，让我们创建一个从Base继承的派生类。因为我们希望派生类能够在实例化对象
// 时设置m_value的值，所以会在Derived构造函数的初始化列表中调用Base构造函数。

// [代码 2]
// class Derived: public Base
// {
// public:
//     Derived(int value)
//         : Base { value }
//     {
//     }
// };

//

// ―――― 向派生类添加新功能 ――――

// 在上面的示例中，由于我们可以访问基类的源代码，因此如果需要，可以直接向Base
// 添加功能。
//
// 有时，我们可能可以访问基类，但不想修改它。考虑这样的情况：您使用了一个外部
// 开源库，但需要一些额外功能。您可以把这些功能添加到原始代码中，但这不是最好
// 的解决方案。如果外部库更新了，该怎么办？要么您的添加内容会被覆盖，要么您必
// 须手动将它们迁移到更新后的代码中，这既耗时又有风险。
//
// 或者，有时甚至不可能修改基类。以标准库中的代码为例，我们无法修改标准库本身
// 的代码。但我们可以从这些类继承，然后将自己的功能添加到派生类中。第三方库也
// 是如此：它们可能只提供头文件，而实现代码已经预编译成二进制文件。
//
// 在这些情况下，最好的做法通常是派生出自己的类，并将需要的功能添加到派生类中。
//
// Base类中一个明显的遗漏是缺少public访问m_value的函数。我们可以通过在Base类中
// 添加访问函数来修正这一点——但为了示例起见，我们将它添加到派生类中。由于
// m_value已在基类中声明为protected，因此Derived可以直接访问它。
//
// 要将新功能添加到派生类中，只需像平常一样在派生类中声明该功能：

// [代码 3]
// class Derived: public Base
// {
// public:
//     Derived(int value)
//         : Base { value }
//     {
//     }
//
//     int getValue() const { return m_value; }
// };

// 现在，在类外部就可以对Derived类型的对象调用getValue()，从而访问m_value的值。

// [代码 4]
// int main()
// {
//     Derived derived { 5 };
//     std::cout << "derived has value " << derived.getValue() << '\n';
//
//     return 0;
// }

// 这将产生以下结果：

// [文本/输出]
// derived has value 5

// 尽管这可能很显然，但Base类型的对象不能访问Derived中的getValue()函数。以下代
// 码无法工作：

// [代码 5]
// int main()
// {
//     Base base { 5 };
//     std::cout << "base has value " << base.getValue() << '\n';
//
//     return 0;
// }

// 这是因为Base中没有getValue()函数。getValue()属于Derived。因为Derived是Base，
// 所以Derived可以访问Base中的内容。然而，Base无权访问Derived中的任何内容。
//

