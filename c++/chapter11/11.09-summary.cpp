// ▼ 问题 1
// 1a) 下面这个程序的输出是什么？为什么？

// [代码 1]
// #include <iostream>
//
// void print(int x)
// {
//     std::cout << "int " << x << '\n';
// }
//
// void print(double x)
// {
//     std::cout << "double " << x << '\n';
// }
//
// int main()
// {
//     short s { 5 };
//     print(s);
//
//     return 0;
// }


// 【答案 · 查看答案】
// 输出是`int 5`。把`short`转换为`int`属于数值提升，而把`short`转换为`double`
// 属于数值转换。在数值提升和数值转换之间，编译器会优先选择数值提升。
//
// 1b) 下面这段代码为什么无法通过编译？

// [代码 2]
// #include <iostream>
//
// void print()
// {
//     std::cout << "void\n";
// }
//
// void print(int x=0)
// {
//     std::cout << "int " << x << '\n';
// }
//
// void print(double x)
// {
//     std::cout << "double " << x << '\n';
// }
//
// int main()
// {
//     print(5.0f);
//     print();
//
//     return 0;
// }


// 【答案 · 查看答案】
// 因为带有默认实参的形参不参与重载函数的匹配判定，编译器无法判断对`print()`的
// 调用应当匹配`print()`还是`print(int x=0)`。
//
// 1c) 下面这段代码为什么无法通过编译？

// [代码 3]
// #include <iostream>
//
// void print(long x)
// {
//     std::cout << "long " << x << '\n';
// }
//
// void print(double x)
// {
//     std::cout << "double " << x << '\n';
// }
//
// int main()
// {
//     print(5);
//
//     return 0;
// }


// 【答案 · 查看答案】
// 字面值5是`int`。把`int`转换为`long`或转换为`double`都属于数值转换，编译器无
// 法判断哪个函数的匹配更好。

