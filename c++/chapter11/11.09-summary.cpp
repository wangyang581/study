// ▼ 问题 3
// 下面这个程序的输出是什么？为什么？

// [代码 10]
// #include <iostream>
//
// template <typename T>
// int count(T) // 等价于 int count(T x)，只是形参没有被使用，所以不给它命名
// {
//     static int c { 0 };
//     return ++c;
// }
//
// int main()
// {
//     std::cout << count(1) << '\n';
//     std::cout << count(1) << '\n';
//     std::cout << count(2.3) << '\n';
//     std::cout << count<double>(1) << '\n';
//
//     return 0;
// }


// 【答案 · 查看答案】
// 输出为：
//
// 第一次调用`count(1)`时，编译器会实例化函数`count<int>(int)`并调用它，返回值
// 为`1`。
//
// 再次调用`count(1)`时，编译器发现`count<int>(int)`已经存在，于是再次调用它，
// 返回值为`2`。
//
// 调用`count(2.3)`时，编译器会实例化原型为`count<double>(double)`的函数并调用
// 它。这是一个新函数，有自己独立的静态变量`c`，因此返回值为`1`。
//
// 调用`count<double>(1)`时，编译器发现我们显式要求使用`count()`的double版本。
// 这个函数由于上一条语句已经存在，因此会调用`count<double>(double)`，而`int`
// 实参会隐式转换为`double`。这个函数会返回`2`。

// ▼ 问题 4
// 下面这个程序的输出是什么？

// [代码 11]
// #include <iostream>
//
// int foo(int n)
// {
//     return n + 10;
// }
//
// template <typename T>
// int foo(T n)
// {
//     return n;
// }
//
// int main()
// {
//     std::cout << foo(1) << '\n'; // #1
//
//     short s { 2 };
//     std::cout << foo(s) << '\n'; // #2
//
//     std::cout << foo<int>(4) << '\n'; // #3
//
//     std::cout << foo<int>(s) << '\n'; // #4
//
//     std::cout << foo<>(6) << '\n'; // #5
//
//     return 0;
// }


// 【答案 · 查看答案】
// 输出为：
//
// 第1种情况：`foo(1)`与`foo(int)`精确匹配，因此调用非模板函数`foo(int)`。
//
// 第2种情况：`foo(s)`与非模板函数`foo(int)`并不精确匹配，但实参`s`可以转换为
// `int`，因此`foo(int)`是候选函数。然而，编译器更倾向于使用函数模板
// `foo<T>(T)`来「刻印」出精确匹配的`foo<short>(short)`。因此这里调用的是
// `foo<short>(short)`。
//
// 第3种情况：`foo<int>(4)`是对`foo<int>`的显式调用，因此不考虑`foo(int)`。编
// 译器刻印出`foo<int>(int)`并调用它。
//
// 第4种情况：这同样是对`foo<int>`的显式调用。编译器把实参`s`提升为`int`以匹配
// 形参。
//
// 第5种情况：这种语法只会匹配函数模板，因此不考虑`foo(int)`。这里调用
// `foo<int>(int)`。
//

