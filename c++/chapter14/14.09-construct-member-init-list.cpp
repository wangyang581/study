// ▼ 问题 3
// 为什么我们把`m_color`写成`std::string`，而不是`std::string_view`？

// 【答案 · 查看答案】
// 在这个例子中，两者其实没有区别（因为我们的颜色实参是C样式字符串字面值，不会
// 离开作用域）。
//
// 但从概念上讲，我们希望`Ball`类拥有传入的颜色。如果`m_color`是
// `std::string_view`，那么当颜色实参传入的是一个临时对象（例如某个函数返回的
// `std::string`）时，一旦这个临时的颜色实参被销毁，`m_color`就会变成悬空的。
//
// 我们会在「13.8 结构体杂项」中更详细地讨论这种情况（并给出示例）。
//

// ==========================================================================
// 可运行示例（来自教程代码块）
// ==========================================================================

#include <iostream>

class Foo
{
private:
    int m_x {};
    int m_y {};

public:
    Foo(int x, int y)
        : m_x { x }, m_y { y } // 这里是 成员初始化列表
    {
        std::cout << "Foo(" << x << ", " << y << ") constructed\n";
    }

    void print() const
    {
        std::cout << "Foo(" << m_x << ", " << m_y << ")\n";
    }
};

int main()
{
    Foo foo{ 6, 7 };
    foo.print();

    return 0;
}
