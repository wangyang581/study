// ▼ 问题 1
// 下面这个程序会打印出什么值？假设short为2字节，且运行在32位机器上。

// [代码 18]
// #include <iostream>
//
// int main()
// {
// 	short value{ 7 }; // &value = 0012FF60
// 	short otherValue{ 3 }; // &otherValue = 0012FF54
//
// 	short* ptr{ &value };
//
// 	std::cout << &value << '\n';
// 	std::cout << value << '\n';
// 	std::cout << ptr << '\n';
// 	std::cout << *ptr << '\n';
// 	std::cout << '\n';
//
// 	*ptr = 9;
//
// 	std::cout << &value << '\n';
// 	std::cout << value << '\n';
// 	std::cout << ptr << '\n';
// 	std::cout << *ptr << '\n';
// 	std::cout << '\n';
//
// 	ptr = &otherValue;
//
// 	std::cout << &otherValue << '\n';
// 	std::cout << otherValue << '\n';
// 	std::cout << ptr << '\n';
// 	std::cout << *ptr << '\n';
// 	std::cout << '\n';
//
// 	std::cout << sizeof(ptr) << '\n';
