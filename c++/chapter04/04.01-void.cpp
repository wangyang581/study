// Void是最容易解释的数据类型。简单来说，void意味着”没有类型”！
//
// Void是不完整类型的第一个例子。不完整类型是已声明但尚未定义的类型。编译器知
// 道这种类型的存在，但没有足够的信息来确定该类型的对象需要分配多少内存。void
// 是有意设计为不完整的，因为它表示的就是类型的缺失，因此无法被定义。
//
// 无法实例化不完整的类型：

// [代码 1]
// void value; // 无法编译，变量无法被定义为不完整的类型

// Void通常用在以下几种不同的场景中。
//

// ―――― 不返回值的函数 ――――

// 最常见的是，void用于指示函数不返回值：

// [代码 2]
// void writeValue(int x) // void 这里代表不返回值
// {
//     std::cout << "The value of x is: " << x << '\n';
//     // 无return语句
// }

// 如果在这样的函数中使用return语句尝试返回值，将会导致编译错误：

// [代码 3]
// void noReturn(int x) // void 这里代表不返回值
// {
//     std::cout << "The value of x is: " << x << '\n';
//
//     return 5; // 会导致编译失败
// }

//

// ―――― 不推荐：不带参数的函数 ――――

// 在C中，void用于表示函数不接受任何参数：

// [代码 4]
// int getValue(void) // void 这里代表没有参数
// {
//     int x{};
//     std::cin >> x;
//
//     return x;
// }

// 尽管这在C++中可以通过编译（出于向后兼容性的原因），但在C++中不推荐这种使用
// void关键字的做法。下面的代码是等效的，也是C++中推荐的写法：

// [代码 5]
// int getValue() // 无参数函数
// {
//     int x{};
//     std::cin >> x;
//
//     return x;
// }

// 最佳实践
//
// 使用空参数列表而不是void来指示函数没有参数。
//

