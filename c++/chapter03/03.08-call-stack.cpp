// 现代调试器还包含一个非常有用的调试信息窗口，即调用堆栈窗口。
//
// 当程序调用函数时，您已经知道它会记录当前的位置，然后跳转到被调用的函数中执
// 行，执行完毕后再返回。那么程序是如何知道该返回到哪里的呢？答案是它通过调用
// 堆栈来保持记录。
//
// 调用堆栈是为到达当前执行点而依次调用的所有函数的列表。调用堆栈包含每个被调
// 用函数的信息，以及函数返回时将回到哪一行的标记。每当调用新函数时，该函数都
// 会被添加到调用堆栈的顶部。当当前函数返回给调用者时，它会从调用堆栈的顶部移
// 除，控制权将返回到它下面的函数。
//
// 调用堆栈窗口是显示当前调用堆栈的调试器窗口。如果看不到调用堆栈窗口，则需要
// 在 IDE 中设置将其显示出来。
//
// 对于Visual Studio用户
//
// 在Visual Studio中，可以通过菜单中的“调试”>“窗口”>“调用堆栈”找到调用堆栈窗口。
// 请注意，您必须处于调试会话中才能激活此窗口。
//
// 让我们使用示例程序来查看调用堆栈：

// [代码 1]
// #include <iostream>
//
// void a()
// {
// 	std::cout << "a() called\n";
// }
//
// void b()
// {
// 	std::cout << "b() called\n";
// 	a();
// }
//
// int main()
// {
// 	a();
// 	b();
//
// 	return 0;
// }

// 在此程序的第5行和第10行上放置断点，然后启动调试模式。因为首先调用的是函数 a，
// 所以程序将首先命中第5行上的断点。
//
// 此时，您应该看到这样的内容：
// [图片] https://www.studycpp.cn/basic/chapter3/call-stack/call-stack.png
// 调用堆栈
//
// 您的IDE显示的内容可能会有一些差异：
// - 函数名和行号的格式可能不同
// - 您的行号可能略有不同（相差1）
// - 您可能会看到许多其他名字奇怪的函数，而不是[外部代码]。
//
// 这些差异无关紧要。
//
// 这里相关的是前两行。从下往上，我们可以看到函数main首先被调用，然后函数a被调
// 用。
//
// 函数 a 旁边的第5行显示了当前执行点的位置（与代码窗口中的执行标记一致）。第
// 二行上的第17行表示当控制权返回到函数 main 时将继续执行的行。
//
// 现在，点击继续，推进到下一个断点，即第10行的断点。调用堆栈应该会更新以反映
// 新的情况：
// [图片] https://www.studycpp.cn/basic/chapter3/call-stack/call-stack1.png
// 调用堆栈
//
// 您会注意到，函数 b 现在位于调用堆栈的顶部，表明函数 b 是当前正在执行的函数。
// 请注意，函数 a 已经不在调用堆栈上了，这是因为函数 a 在返回时已从调用堆栈中
// 移除。
//
// 现在，点击继续，我们将再次命中第5行上的断点（因为函数b调用函数a）。调用堆栈
// 如下所示：
// [图片] https://www.studycpp.cn/basic/chapter3/call-stack/call-stack2.jpg
// 调用堆栈
//
// 现在调用堆栈上有三个函数：（从下到上）main 调用了函数 b，而 b 又调用了函数
// a。
//
// 当断点被命中时，如果您想知道程序是通过哪些函数调用到达代码中该特定位置的，
// 调用堆栈窗口与断点配合使用会非常有帮助。
//
// 提示
//
// 函数名后面的行号显示每个函数中要执行的下一行。
//
// 由于调用堆栈上的顶部条目表示当前正在执行的函数，因此这里的行号显示的是恢复
// 执行时将执行的下一行。调用堆栈中的其余条目表示将来会返回到的函数，因此这些
// 函数的行号表示在函数返回后将执行的下一条语句。
//

