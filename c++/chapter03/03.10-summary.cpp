// ▼ 问题 4
// 附加题：下面这个程序本应把两个数字相加，但运行结果不正确。
//
// 请使用集成调试器单步执行这个程序。输入时分别输入8和4。根据你观察到的信息，
// 修正下面的程序：

// [代码 6]
// #include <iostream>
//
// int readNumber()
// {
//     std::cout << "Please enter a number: ";
//     char x{};
//     std::cin >> x;
//
//     return x;
// }
//
// void writeAnswer(int x)
// {
//     std::cout << "The sum is: " << x << '\n';
// }
//
// int main()
// {
//     int x { readNumber() };
//     int y { readNumber() };
//     writeAnswer(x + y);
//
//     return 0;
// }


// 【答案 · 查看答案】
// 问题出在第6行的`char`数据类型上。当我们输入数字8时，它并不是以值`8`存储的，
// 而是存储为`56`；输入数字4时，存储为`52`。因此`readNumber()`返回的是`56`和
// `52`，而不是期望的`8`和`4`。
//
// 解决办法是把第6行的数据类型从`char`改为`int`。
//

// ==========================================================================
// 可运行示例（来自教程代码块）
// ==========================================================================

#include <iostream>

int readNumber(int x)
{
	std::cout << "Please enter a number: ";
	std::cin >> x;
	return x;
}

void writeAnswer(int x)
{
	std::cout << "The sum is: " << x << '\n';
}

int main()
{
	int x {};
	readNumber(x);
	x = x + readNumber(x);
	writeAnswer(x);

	return 0;
}
