// 软件错误很普遍。出错很容易，定位错误却很难。本章主要讲解如何在C++程序中查找
// 和修复错误，包括如何使用IDE中的集成调试器。
//
// 尽管调试工具和技术不属于C++标准，但查找和修复程序中的错误是成为优秀程序员极
// 其重要的一部分。因此，我们有必要花时间来讨论这些内容，以便随着编写的程序变
// 得更复杂，你诊断和修复问题的能力也能同步提高。
//
// 如果你有使用其他编程语言调试程序的经验，那么会对下面的内容比较熟悉。
