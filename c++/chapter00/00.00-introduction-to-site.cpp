// ―――― 网站目标 ――――

// 教程目标：
// - 通常的编程教程只覆盖C++的基础知识，却很少讲解相关的辅助知识，例如编程风
//   格、常见错误、如何调试、什么是好的编程实践、什么是坏的编程实践、如何测试
//   等。 因此，学完教程后，尽管能编写出可运行的程序，但可能已经养成了错误的
//   编程习惯，后续容易写出不够健壮或易出错的程序。 通过学习本教程，不仅能学
//   会如何使用C++来编写代码，更能学会如何避免编程中的陷阱和缺陷。
// - 本教程提供了大量简洁明确的编程样例。除了文字讲解之外，样例代码能加深对知
//   识点的理解。 必要的知识点都会配有样例代码，并且会避免在样例代码中引入未
//   经介绍的概念。
// - 提供必要的编程练习。章节末尾会有相关的练习题，请自己尝试去解决。 每道题
//   后面都附有答案，可以将你的答案与网站上的答案进行比较，或在思路卡住时参考
//   附带的答案。
// - 编程是一件充满乐趣的事情。如果你并未感受到乐趣，那可能还没有准备好开始学
//   习。 不集中精神时，编写代码非常容易出错，而且调试有问题的代码比一次写对
//   要花更久的时间。 如果在一个问题上卡住很久，不妨休息一下，第二天思路也许
//   就能重新打开。
//

// ―――― 阅读建议 ――――

// - 手动编写样例代码，并且亲手编译运行，不要直接复制粘贴！这样能对容易出错的
//   地方更加了解，并且熟悉编译失败时编译器给出的告警提示「warnings」和错误提
//   示「errors」。 输入代码时，仔细想想每一行代码的含义以及每一行代码对整体
//   的影响。如果碰到任何不理解的地方，这就是需要仔细研究的点。
// - 编写代码时，经常会出现bug。在向其他人寻求帮助之前，尽量尝试自己解决问题。
//   解决代码中的异常错误是编程的重要技能。不要忽视调试器「debugger」的使用（
//   后续章节会进行介绍）。 调试器是找出程序错误的关键工具。
// - 尝试修改样例代码，看看修改后程序的运行结果。例如，原程序是两个数字相加，
//   可以改成三个数字相加。 也可以尝试用不同的方式让程序崩溃，例如程序要求输
//   入一个数字时，尝试输入字符看看会发生什么。这样比只学习样例代码能了解到更
//   多知识。
// - 预留足够的时间来解决章节后的练习题。如果是新手，可能会有些挑战，因为仍处
//   于熟悉阶段，有可能需要多次尝试才能得到正确答案。 如果卡住了，可以参考附
//   带的答案，但要确保完全理解答案后再进行后续的学习。用新学到的概念去编写小
//   程序，可以加深对知识的理解。
