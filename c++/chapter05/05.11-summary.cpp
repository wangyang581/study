//   如果用户输入年龄「18」，只会提取字符`'1'`。由于`1`的ASCII值是`49`，用户
//   会被当成49岁。存储年龄应当使用普通的`int`，因为年龄并不需要某个特定的最
//   小整数宽度。同时还可以删掉`#include <cstdint>`。
