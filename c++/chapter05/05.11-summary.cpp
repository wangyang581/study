//   `16`的`constexpr`变量。
// - 第18行中，`'.\n'`是多字符字面值，会打印出错误的值。它应当使用双引号（
//   `".\n"`）。

// ▼ 问题 3
// `std::string`与`std::string_view`的主要区别是什么？
//
// 使用`std::string_view`时可能会出什么问题？

// 【答案 · 查看答案】
// `std::string`提供的是可修改的字符串，它的初始化和拷贝开销较大。
//
// `std::string_view`提供的是对存在于其他地方的字符串的只读视图，它的初始化和
// 拷贝开销很小。当被观察的字符串在观察它的`std::string_view`之前被销毁时，
// `std::string_view`就可能出问题。

