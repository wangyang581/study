// ▼ 问题 1
// 为什么命名常量往往比字面值常量更好？

// 【答案 · 查看答案】
// 在程序中使用字面值常量（也就是所谓的魔术数字）会让程序更难理解、更难修改。
// 符号常量有助于表明这些数字实际代表什么，而且在声明处修改一个符号常量，就能
// 同时改变它被使用的所有位置。
//
// 为什么const/constexpr变量通常比用`#define`定义的符号常量更好？

// 【答案 · 查看答案】
// `#define`常量不会出现在调试器中，而且更容易发生命名冲突。

