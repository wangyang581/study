// ▼ 问题 1
// 下列各种描述分别属于哪种关系（组合、聚合、关联还是依赖）？
//
// 1a) 一个Animal类，其中包含动物类型（枚举）和名字（string）。

// 【答案 · 查看答案】
// 组合——动物类型和名字在Animal之外没有用处。
//
// 1b) 一个文本编辑器类，其save()函数接受一个File对象作为实参，save()函数把编
// 辑器的内容写到磁盘上。

// 【答案 · 查看答案】
// 依赖——文本编辑器类为了完成「保存到磁盘」这个任务而使用了File对象。
//
// 1c) 一个Adventurer类，可以携带各种Item，例如剑、法杖、药水或法术书。这些
// Item可以被其他Adventurer丢弃或拾取。

// 【答案 · 查看答案】
// 关联——Adventurer与Item之间不是「整体-部分」关系，因此这不是聚合。Adventurer
// 「使用」Item，但不管理它们的存亡。
//
// 1d) Player在Shrine（神殿）中祈祷以获得新的能力。

// 【答案 · 查看答案】
// 依赖——Player依赖神殿来获得能力，但与它没有任何长期关联。
//
// 1e) 一个Computer类，其中包含一个CPU类。这个CPU可以从Computer上拆下来单独测
// 试。

// 【答案 · 查看答案】
// 聚合——计算机「拥有」一个CPU，但不管理它的存亡。
//
// 1f) 铁匠有一块特定的铁砧，用来完成他的工作。

// 【答案 · 查看答案】
// 关联——铁匠使用这块铁砧，但与它之间不是「整体-部分」关系。

// ▼ 问题 2
