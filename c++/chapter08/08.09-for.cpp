// 下面这个for循环有什么问题？

// [代码 18]
// // 打印从 9 到 0 的所有数字
// for (unsigned int i{ 9 }; i >= 0; --i)
//     std::cout << i<< ' ';


// 【答案 · 查看答案】
// 这个for循环在`i >= 0`时持续执行，也就是说它会一直运行到`i`为负数为止。然而
// 由于`i`是无符号的，`i`永远不可能变成负数。因此这个循环会永远运行下去！
//
// 一般来说，除非确有必要，否则最好不要用无符号变量来做循环变量。

