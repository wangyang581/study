// ▼ 问题 1
// 在上面这个程序中，为什么变量`inner`声明在while语句块内部，而不是紧跟在
// `outer`的声明之后？

// 【答案 · 查看答案】
// 把变量inner声明在while语句块内部，是为了让它在每次执行外层循环时都被重新创
// 建（并重新初始化为1）。如果把变量inner声明在外层while循环之前，它的值就永远
// 不会被重置为1，或者我们就必须用赋值语句来重置它。此外，由于变量inner只在外
// 层while循环的语句块中使用，把它声明在那里也更合理。记住，应当把变量声明在尽
// 可能小的作用域中！

