// ―――― 排序的案例 ――――

// 对数组排序是按特定顺序排列数组中所有元素的过程。在许多不同的情况下，对数组
// 进行排序都很有用。例如，电子邮件程序通常按接收时间的顺序显示邮件，因为最近
// 的邮件通常更值得关注。当您打开联系人列表时，姓名通常按字母顺序排列，因为这
// 样更容易找到要查找的姓名。这两个例子都涉及在展示之前对数据进行排序。
//
// 对数组进行排序可以使搜索数组更有效，不仅对人类，对计算机也是如此。例如，考
// 虑这样一种情况，即我们希望知道名称是否出现在名称列表中。为了查看名称是否在
// 列表中，我们必须检查数组中的每个元素，以查看名称是否出现。对于具有多个元素
// 的数组，搜索所有元素可能会非常昂贵。
//
// 然而，现在假设我们的名称数组已经按字母顺序排序。在这种情况下，如果从头遍历
// 到某个名称时，它的字母顺序已经比我们要查找的名称更靠后，而此时仍没有找到目
// 标名称，那么就能知道目标名称不可能存在于数组的其余部分中，因为后续所有名称
// 的字母顺序都只会更靠后！
//
// 事实证明，还有更好的算法可以搜索排序数组。使用一个简单的算法，我们只需20次
// 比较就可以搜索包含1000000个元素的排序数组！当然，缺点是对数组进行排序相对昂
// 贵，除非需要多次搜索，否则通常不值得为了快速搜索而先对数组排序。
//
// 在某些情况下，对数组进行排序可能会使搜索变得不必要。考虑另一个例子，我们希
// 望找到最好的分数。如果数组未排序，我们必须遍历数组中的每个元素，以找到最大
// 的分数。如果列表被排序，最好的分数将在第一个或最后一个位置（取决于我们是按
// 升序还是降序排序），因此根本不需要搜索！
//

// ―――― 排序的工作原理 ――――

// 排序通常通过重复比较成对的数组元素来执行，并在它们满足某些预定义标准时交换
// 它们。根据使用的排序算法，比较元素的顺序会有所不同，同时也取决于列表的排序
// 方式（例如升序或降序）。
//
// 要交换两个元素，可以使用C++标准库中的std::swap()函数，该函数在<utility>头文
// 件中定义。

// [代码 1]
// #include <iostream>
// #include <utility>
//
// int main()
// {
//     int x{ 2 };
//     int y{ 4 };
//     std::cout << "Before swap: x = " << x << ", y = " << y << '\n';
//     std::swap(x, y); // 交换 x 和 y
//     std::cout << "After swap:  x = " << x << ", y = " << y << '\n';
//
//     return 0;
// }

// 该程序打印:

// [代码 2]
// Before swap: x = 2, y = 4
// After swap:  x = 4, y = 2

// 请注意，在交换之后，x和y的值已经互换！
