// ―――― 选择排序 ――――

// 有许多方法可以对数组进行排序。选择排序可能是最容易理解的排序算法，这使它很
// 适合用于教学，尽管它是较慢的排序算法之一。
//
// 选择排序执行以下步骤，以从最小到最大对数组进行排序:
//
// 换句话说，我们将找到数组中最小的元素，并将其交换到第一个位置。然后我们要找
// 到下一个最小的元素，并将其交换到第二个位置。将重复此过程，直到元素用完。
//
// 下面是该算法在5个元素上工作的示例。让我们从一个示例数组开始:
//
// {30、50、20、10、40}
//
// 首先，我们找到最小的元素，从索引0开始:
//
// {30、50、20、10、40}
//
// 然后将其与索引0处的元素交换:
//
// {10、50、20、30、40}
//
// 现在第一个元素已经排序，我们可以忽略它。现在，我们找到最小的元素，从索引1开
// 始:
//
// {10、50、20、30、40}
//
// 并与索引1中的元素交换:
//
// {10、20、50、30、40}
//
// 现在我们可以忽略前两个元素。从索引2开始查找最小元素:
//
// {10、20、50、30、40}
//
// 并与索引2中的元素交换:
//
// {10、20、30、50、40}
//
// 从索引3开始查找最小元素:
//
// {10、20、30、50、40}
//
// 并与索引3中的元素交换:
//
// {10、20、30、40、50}
//
// 最后，从索引4开始找到最小的元素:
//
// {10、20、30、40、50}
//
// 并将其与索引4中的元素交换（该元素不执行任何操作）:
//
// {10、20、30、40、50}
//
// 完成！
//
// {10、20、30、40、50}
//
// 请注意，最后一次比较总是与自身进行比较（这是冗余的），因此我们实际上可以在
// 数组最后一个元素之前停止比较。
//

// ―――― C++实现的选择排序 ――――

// 下面是该算法在C++中的实现方式:

// [代码 3]
// #include <iostream>
// #include <iterator>
// #include <utility>
//
// int main()
// {
// 	int array[]{ 30, 50, 20, 10, 40 };
// 	constexpr int length{ static_cast<int>(std::size(array)) };
//
// 	// 从头遍历
// 	// 但不处理最后一个位置
// 	for (int startIndex{ 0 }; startIndex < length - 1; ++startIndex)
// 	{
// 		// smallestIndex 是遍历时遇到的最小元素的位置
// 		// 开始时，暂定起点位置就是最小元素的位置
// 		int smallestIndex{ startIndex };
//
// 		// 然后遍历数组中后续的元素
// 		for (int currentIndex{ startIndex + 1 }; currentIndex < length; ++currentIndex)
// 		{
// 			// 如果发现一个元素比之前的要小
// 			if (array[currentIndex] < array[smallestIndex])
// 				// 更换记录的位置
// 				smallestIndex = currentIndex;
// 		}
//
// 		// smallestIndex 现在保存的就是最小元素的位置
//         // 将其与开头的元素进行交换 (意味着将它放到了正确的位置)
// 		std::swap(array[startIndex], array[smallestIndex]);
// 	}
//
// 	// 现在数组都排序好了，打印验证一下
// 	for (int index{ 0 }; index < length; ++index)
// 		std::cout << array[index] << ' ';
//
// 	std::cout << '\n';
//
// 	return 0;
// }

// 该算法最令人困惑的部分是循环中的循环（称为嵌套循环）。外层循环（startIndex）
// 逐个迭代每个元素。对于外层循环的每次迭代，内层循环（currentIndex）用于查找
// 剩余数组中的最小元素（从startIndex+1开始）。smallestIndex跟踪内层循环找到的
// 最小元素的索引。然后将smallestIndex对应的元素与startIndex对应的元素交换。最
// 后，外层循环（startIndex）前进一个元素，并重复该过程。
//
// 提示:如果您在理解上面的程序如何工作时遇到困难，可以在纸上手动推演一个示例。
// 将起始（未排序）数组元素横向写在纸的顶部。绘制箭头，指示startIndex、
// currentIndex和smallestIndex当前索引的元素。手动跟踪程序，并在索引更改时重新
// 绘制箭头。对于外层循环的每次迭代，另起一行显示数组的当前状态。
//
// 排序名称使用相同的算法。只需将数组类型从int更改为std::string，并使用适当的
// 值进行初始化。
//

// ―――― std::sort ――――

// 由于排序数组非常常见，C++标准库包含一个名为std::sort的排序函数，该函数位于
// <algorithm>头文件中，并且可以在类似这样的数组上调用:

// [代码 4]
// #include <algorithm> // for std::sort
// #include <iostream>
// #include <iterator> // for std::size
//
// int main()
// {
// 	int array[]{ 30, 50, 20, 10, 40 };
//
// 	std::sort(std::begin(array), std::end(array));
//
// 	for (int i{ 0 }; i < static_cast<int>(std::size(array)); ++i)
// 		std::cout << array[i] << ' ';
//
// 	std::cout << '\n';
//
// 	return 0;
// }

// 默认情况下，std::sort使用操作符<来比较元素对，并按升序排序，在必要时交换它
// 们（与上面的选择排序示例非常相似）。
//
