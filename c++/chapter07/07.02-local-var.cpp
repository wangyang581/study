// #include <iostream>
//
// int main()
// {
//     std::cout << "Enter an integer: ";
//     int smaller{};
//     std::cin >> smaller;
//
//     std::cout << "Enter a larger integer: ";
//     int larger{};
//     std::cin >> larger;
//
//     // 如果用户输错了顺序
//     if (smaller > larger)
//     {
//         // 交换 smaller 与 larger 的值
