// 编写一个程序，要求用户输入两个整数，一个名为`smaller`，另一个名为`larger`。
// 如果用户为第二个整数输入了更小的值，就使用一个语句块和一个临时变量来交换
// `smaller`和`larger`的值。然后打印`smaller`和`larger`变量的值。并在代码中添
// 加注释，标明每个变量的「死亡」位置。注意：打印时，无论输入顺序如何，
// `smaller`都应当保存较小的输入值，`larger`保存较大的输入值。
//
// 程序的输出应与下面一致：

// [文本/输出]
// Enter an integer: 4
// Enter a larger integer: 2
// Swapping the values
// The smaller value is 2
// The larger value is 4


