// ▼ 问题 2
// 变量的作用域、持续时间和生命周期有什么区别？默认情况下，局部变量具有什么作
// 用域和持续时间（它们分别是什么意思）？

// 【答案 · 查看答案】
// 变量的作用域决定了该变量在源代码中的哪些位置可以被访问。持续时间定义了变量
// 何时创建、何时销毁的规则。变量的生命周期则是它从创建到销毁之间的实际时间。
//
// 局部变量具有块作用域，这意味着从它的定义点开始，到它所在语句块的末尾为止都
// 可以访问它。
//
// 局部变量具有自动持续时间，这意味着它在定义点被创建，并在其所在语句块的末尾
// 被销毁。
//

