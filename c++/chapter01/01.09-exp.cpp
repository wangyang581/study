//
// c)

// [代码 8]
// x = 5;


// 【答案 · 查看答案】
// 表达式语句。`x = 5`是对`operator=`的一次调用，它有两个操作数：`x`和`5`。分
// 号使它成为表达式语句。
//
// d) 附加题：

// [代码 9]
// foo(); // foo是一个函数


// 【答案 · 查看答案】
// 函数调用是表达式的一部分，因此这是表达式语句。
//
