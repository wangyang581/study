// ▼ 问题 1
// 初始化和赋值有什么区别？一个变量可以被初始化或赋值多少次？

// 【答案 · 查看答案】
// 初始化是在变量创建时为它提供初始值；赋值是在变量已经定义之后为它赋予新的值。
//
// 由于变量只会被创建一次，因此它只能被初始化一次。而变量可以被赋值任意多次。

// ▼ 问题 2
// 未定义的行为在什么时候发生？未定义的行为会导致什么后果？

// 【答案 · 查看答案】
// 当程序员做了C++语言规范没有明确定义的事情时，就会发生未定义的行为。后果几乎
// 可以是任何情况，从程序崩溃、得到错误答案，到居然正常运行。

